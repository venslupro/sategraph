/**
 * Deterministic demonstration dataset.
 *
 * The platform is designed for live CelesTrak / GCAT / Wikidata ingestion.
 * A live deployment without those credentials still needs a coherent graph, so
 * this seed supplies representative constellations, satellites, organizations,
 * launches and relations. Orbit elements are generated from published Walker
 * parameters and are illustrative, not operational. Named satellites use their
 * real NORAD identifiers where they are public.
 */
import { greenwichSiderealDegrees } from '@satgraph/orbit';
import type { ConfidenceLevel } from '@satgraph/shared-kernel';

export const SEED_EPOCH = '2026-11-10T00:00:00.000000';
export const SEED_EPOCH_DATE = new Date('2026-11-10T00:00:00Z');

export interface SeedOrbit {
  altitudeKm: number;
  inclinationDeg: number;
  raanDeg: number;
  meanAnomalyDeg: number;
  eccentricity: number;
  /** For geostationary satellites the longitude drives the RAAN at epoch. */
  geoLongitudeDeg?: number;
}

export interface SeedSatellite {
  id: string;
  name: string;
  aliases: string[];
  cosparId: string | null;
  jcatId: string | null;
  wikidataId: string | null;
  status: 'ACTIVE' | 'INACTIVE';
  purpose: string;
  country: string;
  operatorId: string;
  manufacturerId: string | null;
  busId: string | null;
  launchId: string | null;
  constellationId: string | null;
  layerId: string;
  system: string | null;
  orbit: SeedOrbit;
  sources: SeedSourceRef[];
}

export interface SeedSourceRef {
  source: string;
  license: string;
  url?: string;
}

export interface SeedOrganization {
  id: string;
  name: string;
  country: string;
  roles: ('OPERATOR' | 'OWNER' | 'MANUFACTURER')[];
}

export interface SeedLaunch {
  id: string;
  name: string;
  date: string;
  vehicle: string;
  site: string;
}

export interface SeedBus {
  id: string;
  name: string;
  manufacturerId: string;
}

export interface SeedConstellation {
  id: string;
  name: string;
  designPattern: string;
  operatorId: string;
  manufacturerId: string | null;
  busId: string | null;
  launchId: string | null;
  color: string;
  purpose: string;
  country: string;
  description: string;
  healthNote: string | null;
  demoSubset: boolean;
  planes: number;
  perPlane: number;
  altitudeKm: number;
  inclinationDeg: number;
  raanOffsetDeg: number;
  phaseOffsetDeg: number;
  extraOrbits: {
    namePattern: string;
    count: number;
    inclinationDeg: number;
    altitudeKm: number;
    geoLongitudesDeg?: number[];
    raanDeg?: number;
  }[];
}

export interface SeedRelayLink {
  relayId: string;
  userId: string;
  system: string;
  evidence: { label: string; source: string; url?: string }[];
}

export interface SeedDataset {
  satellites: SeedSatellite[];
  constellations: SeedConstellation[];
  organizations: SeedOrganization[];
  launches: SeedLaunch[];
  buses: SeedBus[];
  relays: SeedRelayLink[];
  /** Additional curated relations that are not generated by rules. */
  curatedRelations: {
    type: 'DOCKED_TO' | 'FORMATION_WITH' | 'SUCCEEDS' | 'OWNED_BY';
    fromId: string;
    toId: string;
    label: string;
    confidence: ConfidenceLevel;
    method: string;
    evidence: { label: string; source: string; url?: string }[];
  }[];
  sources: {
    id: string;
    label: string;
    license: string;
    dataTime: string;
    status: 'OK' | 'DEGRADED';
    message: string | null;
  }[];
}

