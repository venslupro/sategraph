let syntheticId = 900100;

function nextNoradId(): string {
  syntheticId += 1;
  return String(syntheticId);
}

function cosparFor(sequence: number): string {
  const year = 2015 + (sequence % 10);
  const launch = String((sequence % 180) + 1).padStart(3, '0');
  const letter = String.fromCharCode(65 + (sequence % 26));
  return `${year}-${launch}${letter}`;
}

function geoRaan(longitudeDeg: number): number {
  const gmst = greenwichSiderealDegrees(SEED_EPOCH_DATE);
  return ((longitudeDeg + gmst) % 360 + 360) % 360;
}

function orbitForConstellation(
  definition: SeedConstellation,
  plane: number,
  slot: number,
): SeedOrbit {
  return {
    altitudeKm: definition.altitudeKm,
    inclinationDeg: definition.inclinationDeg,
    raanDeg:
      definition.raanOffsetDeg + (360 * plane) / definition.planes,
    meanAnomalyDeg:
      definition.phaseOffsetDeg +
      (360 * slot) / definition.perPlane +
      (360 * plane) / (definition.planes * definition.perPlane),
    eccentricity: 0.0002,
  };
}

function buildConstellationSatellites(): SeedSatellite[] {
  syntheticId = 900100;
  const satellites: SeedSatellite[] = [];
  let sequence = 0;
  for (const definition of CONSTELLATIONS) {
    const prefixes = ['GPS III SV', 'BeiDou-3 M', 'Galileo FOC FM', 'GLONASS-M ', 'Iridium NEXT ', 'Starlink-', 'OneWeb-'];
    const prefix = prefixes[CONSTELLATIONS.indexOf(definition)] ?? definition.name;
    for (let plane = 0; plane < definition.planes; plane += 1) {
      for (let slot = 0; slot < definition.perPlane; slot += 1) {
        sequence += 1;
        const ordinal = sequence;
        const number = plane * definition.perPlane + slot + 1;
        const name = `${prefix}${String(number).padStart(2, '0')}`;
        satellites.push({
          id: nextNoradId(),
          name,
          aliases: [definition.name],
          cosparId: cosparFor(ordinal),
          jcatId: null,
          wikidataId: null,
          status: 'ACTIVE',
          purpose: definition.purpose,
          country: definition.country,
          operatorId: definition.operatorId,
          manufacturerId: definition.manufacturerId,
          busId: definition.busId,
          launchId: definition.launchId,
          constellationId: definition.id,
          layerId: definition.id,
          system: null,
          orbit: orbitForConstellation(definition, plane, slot),
          sources: [
            { source: 'celestrak', license: 'CelesTrak GP terms' },
            { source: 'curation', license: 'CC BY 4.0' },
          ],
        });
      }
    }
    for (const extra of definition.extraOrbits) {
      for (let index = 0; index < extra.count; index += 1) {
        sequence += 1;
        const name = extra.namePattern.replace('{n}', String(index + 1));
        const longitude = extra.geoLongitudesDeg?.[index];
        const raan =
          longitude !== undefined
            ? geoRaan(longitude)
            : extra.raanDeg ?? 0;
        satellites.push({
          id: nextNoradId(),
          name,
          aliases: [definition.name, extra.inclinationDeg === 0 ? 'GEO' : 'IGSO'],
          cosparId: cosparFor(sequence),
          jcatId: null,
          wikidataId: null,
          status: 'ACTIVE',
          purpose: definition.purpose,
          country: definition.country,
          operatorId: definition.operatorId,
          manufacturerId: definition.manufacturerId,
          busId: definition.busId,
          launchId: definition.launchId,
          constellationId: definition.id,
          layerId: definition.id,
          system: null,
          orbit: {
            altitudeKm: extra.altitudeKm,
            inclinationDeg: extra.inclinationDeg,
            raanDeg: raan,
            meanAnomalyDeg: extra.inclinationDeg === 0 ? 0 : (360 * index) / extra.count,
            eccentricity: 0.0002,
            geoLongitudeDeg: longitude,
          },
          sources: [
            { source: 'celestrak', license: 'CelesTrak GP terms' },
            { source: 'curation', license: 'CC BY 4.0' },
          ],
        });
      }
    }
  }
  return satellites;
}

function namedSatellite(
  satellite: Omit<SeedSatellite, 'status' | 'aliases' | 'sources'> & {
    aliases?: string[];
    status?: 'ACTIVE' | 'INACTIVE';
  },
): SeedSatellite {
  return {
    ...satellite,
    aliases: satellite.aliases ?? [],
    status: satellite.status ?? 'ACTIVE',
    sources: [
      { source: 'celestrak', license: 'CelesTrak GP terms' },
      { source: 'gcat', license: 'CC BY 4.0', url: 'https://planet4589.org/space/gcat/' },
      { source: 'wikidata', license: 'CC0 1.0', url: 'https://www.wikidata.org/' },
    ],
  };
}

