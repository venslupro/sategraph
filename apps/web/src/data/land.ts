const DEG = Math.PI / 180;

function inPolygon(lon: number, lat: number, poly: readonly LonLat[]): boolean {
  let inside = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i, i += 1) {
    const [xi, yi] = poly[i];
    const [xj, yj] = poly[j];
    if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) {
      inside = !inside;
    }
  }
  return inside;
}

export function isLand(lon: number, lat: number): boolean {
  if (lat < -71) {
    return true;
  }
  if (lat < -63 && lon > -75 && lon < -56) {
    return true;
  }
  return LAND.some((polygon) => inPolygon(lon, lat, polygon));
}

/** Builds the dot lattice in unit-sphere coordinates. */
export function buildLandDots(step = 1.7): Float32Array {
  const points: number[] = [];
  for (let lat = -88; lat <= 88; lat += step) {
    const cosine = Math.cos(lat * DEG);
    const lonStep = step / Math.max(cosine, 0.12);
    for (let lon = -180; lon < 180; lon += lonStep) {
      if (!isLand(lon, lat)) {
        continue;
      }
      const phi = lat * DEG;
      const lambda = lon * DEG;
      points.push(
        Math.cos(phi) * Math.cos(lambda),
        Math.cos(phi) * Math.sin(lambda),
        Math.sin(phi),
      );
    }
  }
  return new Float32Array(points);
}

/** Converts a geodetic coordinate to the three.js unit-sphere frame. */
export function geoToUnit(lonDeg: number, latDeg: number, radius = 1): [number, number, number] {
  const phi = latDeg * DEG;
  const lambda = lonDeg * DEG;
  return [
    radius * Math.cos(phi) * Math.cos(lambda),
    radius * Math.sin(phi),
    -radius * Math.cos(phi) * Math.sin(lambda),
  ];
}
