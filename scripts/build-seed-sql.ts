/**
 * Generates `db/migrations/0002_seed.sql` from the deterministic seed snapshot.
 * The migration only touches the D1 search projection and event log; graph
 * data is published to Neo4j by the scheduler.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildReadModels, buildSeedSnapshot } from '@satgraph/publishing';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUTPUT = join(ROOT, 'db', 'migrations', '0002_seed.sql');

function text(value: string | null | undefined): string {
  if (value === null || value === undefined) {
    return 'NULL';
  }
  return `'${value.replaceAll("'", "''")}'`;
}

function json(value: unknown): string {
  return text(JSON.stringify(value));
}

const snapshot = buildSeedSnapshot();
const models = buildReadModels(snapshot);

const statements: string[] = [
  '-- Generated by scripts/build-seed-sql.ts. Do not edit by hand.',
  `-- Snapshot ${snapshot.graphVersion} / orbits ${snapshot.orbitVersion}.`,
  '',
  'DELETE FROM satellite_search;',
  'DELETE FROM domain_event;',
  '',
];

for (const entry of models.catalog) {
  statements.push(
    [
      'INSERT INTO satellite_search',
      '  (id, name, aliases, cospar_id, norad_id, layer_id, purpose, status,',
      '   constellation_name, orbit_class, data_json)',
      'VALUES (',
      [
        text(entry.id),
        text(entry.name),
        text(entry.aliases.join(', ')),
        text(entry.cosparId),
        text(entry.noradId),
        text(entry.layerId),
        text(entry.purpose),
        text(entry.status),
        text(entry.constellationName),
        text(entry.orbitClass),
        json(entry),
      ].join(',\n       '),
      ');',
      '',
    ].join('\n'),
  );
}

for (const event of models.events) {
  statements.push(
    [
      'INSERT INTO domain_event',
      '  (id, type, occurred_at, aggregate_id, title, detail, graph_version, data_json)',
      'VALUES (',
      [
        text(event.id),
        text(event.type),
        text(event.occurredAt),
        text(event.aggregateId),
        text(event.title),
        text(event.detail),
        text(event.graphVersion),
        json(event),
      ].join(',\n       '),
      ');',
      '',
    ].join('\n'),
  );
}

mkdirSync(dirname(OUTPUT), { recursive: true });
writeFileSync(OUTPUT, `${statements.join('\n')}\n`, 'utf8');
process.stdout.write(
  `Wrote ${OUTPUT}: ${models.catalog.length} satellites, ` +
    `${models.events.length} events.\n`,
);
